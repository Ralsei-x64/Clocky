"""Rebuild the bundled clock glyphs using HarfBuzz and the original Google Fonts."""

import itertools
import json
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path


def make_font(directory, filename, characters, variation="", features=""):
    font = str(directory / filename)
    options = ["--font-size=1000", "--variations=" + variation, "--features=" + features]
    chars = sorted(set(characters))
    pairs = ["".join(pair) for pair in itertools.product(chars, repeat=2)]
    runs = chars + pairs
    result = subprocess.check_output(
        ["hb-shape", *options, "-O", "json", font], input="\n".join(runs) + "\n", text=True
    )
    advances = {
        run: sum(g["ax"] for g in json.loads(line))
        for run, line in zip(runs, result.splitlines(), strict=True)
    }
    glyphs = {}
    for char in chars:
        svg = subprocess.check_output(
            ["hb-vector", *options, "--margin=0", "-O", "svg", font, char]
        )
        path = ET.fromstring(svg).find(".//{*}path")
        glyphs[char] = [advances[char], path.get("d") if path is not None else ""]
    kerning = {}
    for pair in pairs:
        adjustment = advances[pair] - advances[pair[0]] - advances[pair[1]]
        if adjustment:
            kerning[pair] = adjustment
    return {"glyphs": glyphs, "kerning": kerning}


if __name__ == "__main__":
    directory = Path(sys.argv[1])
    digits = "0123456789:"
    months = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec"
    fonts = {
        "serif": make_font(directory, "InstrumentSerif-Regular.ttf", digits + "/"),
        "wide": make_font(directory, "Syne[wght].ttf", digits, "wght=800", "lnum"),
        "mintTime": make_font(directory, "SUSE[wght].ttf", digits, "wght=500"),
        "mintDate": make_font(directory, "SUSE[wght].ttf", digits + months, "wght=400"),
        "russo": make_font(directory, "RussoOne-Regular.ttf", digits),
        "shareTech": make_font(directory, "ShareTech-Regular.ttf", digits[:-1] + months),
        "flux": make_font(directory, "FluxVF.ttf", digits[:-1], "wdth=900"),
    }
    destination = Path(__file__).resolve().parents[1] / "dev.clocky.neo.sdPlugin/assets/glyphs.js"
    destination.write_text("// Generated by tools/make-glyphs.py\nconst clockFonts = "
                           + json.dumps(fonts, indent=2) + ";\n"
                           + 'if (typeof module === "object") module.exports = clockFonts;\n')
